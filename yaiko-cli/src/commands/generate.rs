pub async fn middleware(name: &str) -> anyhow::Result<()> {
    println!("[*] Generating middleware: {}", name.green());
    
    let middleware_dir = Path::new("src/middleware");
    if !middleware_dir.exists() {
        fs::create_dir_all(middleware_dir)?;
    }
    
    let filename = format!("{}.rs", name.to_lowercase());
    let filepath = middleware_dir.join(&filename);
    
    if filepath.exists() {
        println!("{} Middleware already exists: {}", "!".yellow(), filename);
        return Ok(());
    }
    
    let pascal_name = to_pascal_case(name);
    
    let content = format!(
r#"//! {} Middleware
//! Generated by Yaiko CLI

use yaiko_core::{{Request, Response, Handler, Middleware}};
use async_trait::async_trait;
use std::sync::Arc;

pub struct {};

impl {} {{
    pub fn new() -> Self {{
        {}
    }}
}}

#[async_trait]
impl Middleware for {} {{
    async fn handle(
        &self,
        req: Request,
        next: Arc<dyn Handler>,
    ) -> Result<Response, Box<dyn std::error::Error + Send + Sync>> {{
        tracing::debug!("{} middleware: before");
        let response = next.handle(req).await?;
        tracing::debug!("{} middleware: after");
        Ok(response)
    }}
}}
"#, pascal_name, pascal_name, pascal_name, pascal_name, pascal_name, pascal_name, pascal_name);
    
    fs::write(&filepath, content)?;
    
    let mod_path = middleware_dir.join("mod.rs");
    let mod_content = if mod_path.exists() {
        fs::read_to_string(&mod_path)?
    } else {
        String::new()
    };
    
    if !mod_content.contains(&format!("pub mod {};", name.to_lowercase())) {
        let new_mod = format!("{}pub mod {};\npub use {}::{};\n", 
            mod_content, 
            name.to_lowercase(), 
            name.to_lowercase(),
            pascal_name
        );
        fs::write(&mod_path, new_mod)?;
    }
    
    println!("[OK] Created: src/middleware/{}", filename);
    println!("  Add to your router with .use_middleware({})\n", pascal_name);
    
    Ok(())
}

fn to_pascal_case(s: &str) -> String {
    s.split('_')
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                None => String::new(),
                Some(first) => first.to_uppercase().chain(chars).collect(),
            }
        })
        .collect()
}
