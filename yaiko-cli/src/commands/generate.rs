use std::fs;
use std::path::Path;
use colored::Colorize;

pub async fn controller(name: &str) -> anyhow::Result<()> {
    println!("[*] Generating controller: {}", name.green());
    
    let controllers_dir = Path::new("src/controllers");
    if !controllers_dir.exists() {
        fs::create_dir_all(controllers_dir)?;
    }
    
    let filename = format!("{}.rs", name.to_lowercase());
    let filepath = controllers_dir.join(&filename);
    
    if filepath.exists() {
        println!("{} Controller already exists: {}", "!".yellow(), filename);
        return Ok(());
    }
    
    let pascal_name = to_pascal_case(name);
    
    let content = format!(
r#"//! {} Controller
//! Generated by Yaiko CLI

use yaiko_core::{{Request, Response, StatusCode, json}};

pub async fn list(_req: Request) -> Result<Response, Box<dyn std::error::Error + Send + Sync>> {{
    let items: Vec<serde_json::Value> = vec![];
    Ok(Response::new().json(&json!({{ "{}s": items }}))?)
}}

pub async fn get(req: Request) -> Result<Response, Box<dyn std::error::Error + Send + Sync>> {{
    let id = req.param("id").map(|s| s.as_str()).unwrap_or("0");
    Ok(Response::new().json(&json!({{ "id": id, "message": "{} found" }}))?)
}}

pub async fn create(mut req: Request) -> Result<Response, Box<dyn std::error::Error + Send + Sync>> {{
    let body = req.json().await?;
    Ok(Response::new()
        .status(StatusCode::CREATED)
        .json(&json!({{ "message": "{} created", "{}": body }}))?)
}}

pub async fn update(mut req: Request) -> Result<Response, Box<dyn std::error::Error + Send + Sync>> {{
    let id = req.param("id").map(|s| s.as_str()).unwrap_or("0");
    let body = req.json().await?;
    Ok(Response::new().json(&json!({{ "message": "{} updated", "id": id, "{}": body }}))?)
}}

pub async fn delete(req: Request) -> Result<Response, Box<dyn std::error::Error + Send + Sync>> {{
    let id = req.param("id").map(|s| s.as_str()).unwrap_or("0");
    Ok(Response::new().json(&json!({{ "message": "{} deleted", "id": id }}))?)
}}
"#, pascal_name, name, pascal_name, pascal_name, name, pascal_name, name, pascal_name);
    
    fs::write(&filepath, content)?;
    
    let mod_path = controllers_dir.join("mod.rs");
    let mod_content = if mod_path.exists() {
        fs::read_to_string(&mod_path)?
    } else {
        String::new()
    };
    
    if !mod_content.contains(&format!("pub mod {};", name.to_lowercase())) {
        let new_mod = format!("{}pub mod {};\n", mod_content, name.to_lowercase());
        fs::write(&mod_path, new_mod)?;
    }
    
    println!("[OK] Created: src/controllers/{}", filename);
    println!("  Don't forget to add routes in main.rs!\n");
    
    Ok(())
}

